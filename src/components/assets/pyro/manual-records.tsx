"use client";

/**
 * Manual records (D4-OSW-PE-PYR Rev. 02 Table 6.4): oil laboratory results and
 * matched handheld shell scans, kept as dated records with method, place,
 * operator and review status — outside the 161 online entries.
 */

import React from "react";
import { Table, type Column } from "@/components/ui";
import { simTimeMs } from "@/lib/kiln-sim/engine";
import { formatLocalTime } from "@/lib/time";
import type { ManualRecord } from "@/lib/plant-defs";

export function ManualRecords({ records, timeZone }: { records: ManualRecord[]; timeZone?: string | null }) {
  const when = (t: number) => formatLocalTime(simTimeMs(t), { date: true, seconds: false, timeZone });
  const cols: Column<ManualRecord>[] = [
    { key: "t", header: "Taken", width: "150px", render: (r) => <span className="ast-num">{when(r.t)}</span> },
    {
      key: "tag",
      header: "Record",
      width: "230px",
      render: (r) => (
        <span className="ast-cell-stack">
          <span className="ast-cell-title ast-num">{r.tag}</span>
          <span className="ast-cell-sub">{r.where}</span>
        </span>
      ),
    },
    {
      key: "value",
      header: "Result",
      width: "110px",
      render: (r) => (
        <span className="ast-num">
          {r.value} <span className="ast-unit">{r.unit}</span>
        </span>
      ),
    },
    {
      key: "fields",
      header: "Record fields",
      render: (r) => (
        <span className="ast-cell-stack">
          <span className="ast-cell-text">{r.fields.map((f) => `${f.label} ${f.value}`).join(" · ")}</span>
          <span className="ast-cell-sub">{r.method}</span>
        </span>
      ),
    },
    {
      key: "by",
      header: "Operator / simulated review",
      width: "240px",
      render: (r) => (
        <span className="ast-cell-stack">
          <span className="ast-cell-text">{r.by}</span>
          <span className="ast-cell-sub">{r.reviewedBy && r.reviewedAt !== undefined ? `Simulated review · ${r.reviewedBy} · ${when(r.reviewedAt)}` : `${r.review} · simulated`}</span>
        </span>
      ),
    },
  ];
  return (
    <section className="ast-card pg-table-card" aria-label="Manual records">
      <div className="ast-card-head">
        <h2 className="ast-card-title">
          Manual records
          <span className="ast-caption ast-num">{records.length} dated records · D4 Table 6.4 · entered, never replaced by a live sensor · simulated demo records · reviews generated by the simulation, not a user sign-off</span>
        </h2>
      </div>
      <Table columns={cols} data={records} keyExtractor={(r) => r.id} />
    </section>
  );
}
