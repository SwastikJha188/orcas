"""Write the fault-library migration from faults.json (structure.py) and rule-links.json.

usage: python3 -I gen-sql.py <faults.json> <rule-links.json> <fixtures dir> <out.sql>
"""
import json
import os
import sys

faults = json.load(open(sys.argv[1], encoding="utf-8"))["faults"]
links = {k: v for k, v in json.load(open(sys.argv[2], encoding="utf-8")).items() if not k.startswith("_")}
fx = sys.argv[3]
out = sys.argv[4]

# --- checks against the fixture -----------------------------------------------------------------------------------
meas_cols = next(t for t in json.load(open(os.path.join(fx, "manifest.json")))["tables"] if t["name"] == "measurements")["columns"]
rule_cols = next(t for t in json.load(open(os.path.join(fx, "manifest.json")))["tables"] if t["name"] == "rules")["columns"]
mi, ti = meas_cols.index("id"), meas_cols.index("tag")
tags = {}
for r in json.load(open(os.path.join(fx, "measurements.json"))):
    if r[mi].startswith("PYR-"):
        tags.setdefault(r[ti], []).append(r[mi])
dup = {t: v for t, v in tags.items() if len(v) > 1}
assert not dup, f"tag on two pyro machines: {dup}"
ri, ci = rule_cols.index("machine_id"), rule_cols.index("code")
codes = {r[ci] for r in json.load(open(os.path.join(fx, "rules.json"))) if r[ri].startswith("PYR-")}
ids = {f["id"] for f in faults}
missing_codes = sorted(set(links) - codes)
assert not missing_codes, f"rule codes not in the DB: {missing_codes}"
bad = sorted({fid for v in links.values() for fid in v if fid not in ids})
assert not bad, f"unknown fault ids: {bad}"
for f in faults:
    for t in f["primary"] + f["support"]:
        assert t in tags, f"{f['id']}: {t} not a pyro measurement"


def q(v):
    if v is None or v == "":
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


COLS = [
    ("id", "id"), ("machine_id", "machine"), ("group_code", "group"), ("component", "component"), ("title", "title"),
    ("origin", "origin"), ("rev_status", "status"),
    ("applicability", "applicability"), ("primary_text", "primaryText"), ("support_text", "supportText"),
    ("baseline", "baseline"), ("setpoints", "setpoints"), ("detection", "detection"), ("evidence_rule", "evidence"),
    ("what", "what"), ("where_text", "where"), ("alternatives", "why"), ("impact", "impact"),
    ("developing", "developing"), ("alert", "alert"), ("danger", "danger"), ("confidence", "confidence"),
    ("prognosis", "prognosis"), ("analysis", "analysis"), ("discriminate", "discriminate"),
    ("action", "action"), ("check_text", "check"), ("source", "source"), ("retired_reason", "retiredReason"),
    ("sort_order", "order"),
]

sql = []
sql.append("""-- =============================================================================
-- 032 · Pyro-line fault library (OSW-PE-FLT-PYR-01 Rev. 01, 20 Oct 2026)
--
-- One row per fault reference sheet of "ULTRON Pyro-Line Fault Library —
-- Diagnosis · Prognosis · Analysis": 302 active entries (FP-01…FP-47 from D5,
-- UL-<group>-nnn engineering candidates, UL-BGH-nnn main baghouse, DQ-nnn data
-- quality, CX-EXH-nnn conditional) and the 9 retired ESP entries (no ESP is
-- installed, MoM-02), kept for traceability. Text is as printed in the sheet
-- fields 01–11; set-points are the proposals of sensor list OSW-PE-SNL-PYR-01
-- Rev. 01 (not commissioned).
--
--   fault_library         the sheet (machine NULL = line-wide: shared, DQ,
--                         conditional and retired entries)
--   fault_library_inputs  field 02: primary and support measurements
--   rule_faults           which library entries each pyro rule implements
--
-- Generated by scripts/fault-library (parse.py → structure.py → gen-sql.py).
-- =============================================================================

CREATE TABLE IF NOT EXISTS fault_library (
  id VARCHAR(16) PRIMARY KEY,
  plant_id VARCHAR(64) NOT NULL REFERENCES plants(id) ON DELETE CASCADE,
  machine_id VARCHAR(64) REFERENCES machines(id) ON DELETE SET NULL,
  document VARCHAR(64) NOT NULL DEFAULT 'OSW-PE-FLT-PYR-01 Rev. 01',
  group_code VARCHAR(16) NOT NULL,
  component VARCHAR(160) NOT NULL,
  title VARCHAR(200) NOT NULL,
  origin VARCHAR(64) NOT NULL,
  rev_status VARCHAR(24) NOT NULL CHECK (rev_status IN ('Unchanged', 'Inputs updated', 'Re-scoped', 'Converted', 'New', 'Conditional', 'Retired')),
  applicability TEXT,
  primary_text TEXT,
  support_text TEXT,
  baseline TEXT,
  setpoints TEXT,
  detection TEXT,
  evidence_rule TEXT,
  what TEXT,
  where_text TEXT,
  alternatives TEXT,
  impact TEXT,
  developing TEXT,
  alert TEXT,
  danger TEXT,
  confidence TEXT,
  prognosis TEXT,
  analysis TEXT,
  discriminate TEXT,
  action TEXT,
  check_text TEXT,
  source TEXT,
  retired_reason TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS fault_library_machine_idx ON fault_library (machine_id);

CREATE TABLE IF NOT EXISTS fault_library_inputs (
  fault_id VARCHAR(16) NOT NULL REFERENCES fault_library(id) ON DELETE CASCADE,
  measurement_id VARCHAR(128) NOT NULL REFERENCES measurements(id) ON DELETE CASCADE,
  role VARCHAR(8) NOT NULL CHECK (role IN ('primary', 'support')),
  sort_order SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY (fault_id, measurement_id)
);
CREATE INDEX IF NOT EXISTS fault_library_inputs_measurement_idx ON fault_library_inputs (measurement_id);

CREATE TABLE IF NOT EXISTS rule_faults (
  rule_id INTEGER NOT NULL REFERENCES rules(id) ON DELETE CASCADE,
  fault_id VARCHAR(16) NOT NULL REFERENCES fault_library(id) ON DELETE CASCADE,
  sort_order SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY (rule_id, fault_id)
);
""")

names = ", ".join(["plant_id"] + [c for c, _ in COLS])
sql.append(f"INSERT INTO fault_library ({names}) VALUES")
rows = []
for f in faults:
    rows.append("  (" + ", ".join(["'plant-pyro'"] + [q(f.get(k)) for _, k in COLS]) + ")")
sql.append(",\n".join(rows))
upd = ", ".join(f"{c} = EXCLUDED.{c}" for c, _ in COLS if c != "id")
sql.append(f"ON CONFLICT (id) DO UPDATE SET {upd};\n")

sql.append("DELETE FROM fault_library_inputs WHERE fault_id IN (SELECT id FROM fault_library WHERE plant_id = 'plant-pyro');")
vals = []
for f in faults:
    n = 0
    for role in ("primary", "support"):
        for t in f[role]:
            if role == "support" and t in f["primary"]:
                continue
            n += 1
            vals.append(f"  ({q(f['id'])}, {q(t)}, '{role}', {n})")
sql.append("INSERT INTO fault_library_inputs (fault_id, measurement_id, role, sort_order)\nSELECT v.fault_id, m.id, v.role, v.sort_order FROM (VALUES")
sql.append(",\n".join(vals))
sql.append(") AS v(fault_id, tag, role, sort_order)\nJOIN measurements m ON m.tag = v.tag AND m.id LIKE 'PYR-%'\nON CONFLICT DO NOTHING;\n")

sql.append("DELETE FROM rule_faults WHERE rule_id IN (SELECT id FROM rules WHERE machine_id LIKE 'PYR-%');")
vals = [f"  ({q(code)}, {q(fid)}, {k + 1})" for code, fids in links.items() for k, fid in enumerate(fids)]
sql.append("INSERT INTO rule_faults (rule_id, fault_id, sort_order)\nSELECT r.id, v.fault_id, v.sort_order FROM (VALUES")
sql.append(",\n".join(vals))
sql.append(") AS v(code, fault_id, sort_order)\nJOIN rules r ON r.code = v.code AND r.machine_id LIKE 'PYR-%'\nON CONFLICT DO NOTHING;\n")

sql.append("""-- Rev. 01 §8: no electrostatic precipitator is installed; the gas leaves the ID fan for the main baghouse BGH-01.
UPDATE rules
   SET consequence = 'Fuel loss, reducing conditions and CO trip risk at the main baghouse'
 WHERE machine_id = 'PYR-PHC-01' AND code = 'SW-PHC-02';
""")

open(out, "w", encoding="utf-8").write("\n".join(sql))
print("wrote", out, "faults", len(faults), "rule links", sum(len(v) for v in links.values()))
